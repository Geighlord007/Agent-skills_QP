# -*- coding: utf-8 -*-
"""Concurrent OpenAI-compatible vision/chat API runner for dispatch books.

Reads dispatch markdown files generated by build_dispatch.py, sends each group
to an OpenAI-compatible /chat/completions endpoint in parallel, and writes the
corresponding draft / patch / issue files.
"""
import argparse
import base64
import io
import json
import os
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import requests

if sys.platform == "win32":
    for _s in (sys.stdout, sys.stderr):
        if hasattr(_s, "reconfigure"):
            _s.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_KEY_FILE = Path.home() / ".agents" / "keys" / "mimo.key"
DEFAULT_BASE_URL = "https://api.xiaomimimo.com/v1"
DEFAULT_MODEL = "mimo-v2.6-pro"

# Only strip genuine XML tool-call tag lines accidentally leaked by models,
# never normal prose containing words like "parameter" or "parametric".
TOOL_TAG_LINE_RE = re.compile(
    r"^\s*</?(?:antml:[a-zA-Z0-9_:-]+|function_calls|invoke|parameter)\b",
    re.IGNORECASE,
)


def resolve_endpoint(base_url: str) -> str:
    url = base_url.strip().rstrip("/")
    if url.endswith("/chat/completions"):
        return url
    return f"{url}/chat/completions"


def resolve_api_key(cli_key: str, key_file: str) -> str:
    if cli_key:
        return cli_key.strip()
    for env_name in ("MIMO_API_KEY", "OPENAI_API_KEY"):
        val = os.getenv(env_name, "").strip()
        if val:
            return val
    kf = Path(key_file).expanduser()
    if kf.is_file():
        val = kf.read_text(encoding="utf-8").strip()
        if val:
            return val
    sys.exit(
        "缺少 API 密钥：请设置环境变量 MIMO_API_KEY / OPENAI_API_KEY，"
        f"或通过 --api-key / --key-file 提供（默认文件 {kf} 不存在）。\n"
        "若无外部 API 密钥，可改用原生子代理模式（见 references/subagent-prompt-template.md Part 5）。"
    )


def build_images(img_dir: str, pages: list) -> list:
    content = []
    base = Path(img_dir)
    for p in pages:
        fp = base / f"slide-{p:02d}.jpg"
        if not fp.is_file():
            sys.exit(f"页面图不存在: {fp}")
        b64 = base64.b64encode(fp.read_bytes()).decode("ascii")
        content.append({
            "type": "image_url",
            "image_url": {"url": f"data:image/jpeg;base64,{b64}"},
        })
    return content


def call_model(endpoint: str, model: str, text: str, images: list, key: str, temperature: float):
    body = {
        "model": model,
        "temperature": temperature,
        "messages": [
            {"role": "user", "content": [{"type": "text", "text": text}] + images}
        ],
    }
    headers = {"Authorization": f"Bearer {key}", "Content-Type": "application/json"}
    last = None
    r = None
    for attempt in range(3):
        try:
            r = requests.post(endpoint, headers=headers, json=body, timeout=600)
            break
        except requests.RequestException as e:
            last = e
            time.sleep(3 * (attempt + 1))
    else:
        sys.exit(f"接口网络错误（已重试 3 次）: {type(last).__name__}: {last}")

    if r.status_code != 200:
        sys.exit(f"接口错误 {r.status_code}: {r.text[:300]}")
    j = r.json()
    choices = j.get("choices") or []
    if not choices or "message" not in choices[0]:
        sys.exit(f"接口返回格式异常: {str(j)[:300]}")
    return choices[0]["message"].get("content", ""), j.get("usage", {})


def strip_fence(text: str) -> str:
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```[a-zA-Z0-9_-]*\r?\n", "", t)
        t = re.sub(r"\r?\n```$", "", t)
    return t.strip() + "\n"


def sanitize_markdown(text: str) -> str:
    # 只保留第一个 key 标记之后的内容，并精确剔除偶发混入的 XML 工具调用标签行
    t = strip_fence(text)
    first = t.find("<!--key:")
    if first < 0:
        sys.exit(f"输出里没有 key 标记: {t[:200]}")
    t = t[first:]
    clean = [line for line in t.splitlines() if not TOOL_TAG_LINE_RE.search(line)]
    return "\n".join(clean).rstrip("\n") + "\n"


def extract_json(text: str) -> dict:
    t = strip_fence(text)
    m = re.search(r"\{.*\}", t, re.S)
    if not m:
        sys.exit(f"输出里没有 JSON: {t[:200]}")
    return json.loads(m.group(0))


def one_task(role: str, endpoint: str, model: str, key: str, gdir: Path, item: dict, images_dir: str):
    gi = item["group"]
    pages = item["pages"]
    if role == "translate":
        book = (gdir / f"dispatch-tr-{gi:02d}.md").read_text(encoding="utf-8")
        imgs = build_images(images_dir, pages) if images_dir else []
        out = gdir / f"draft-{gi:02d}.md"
        content, usage = call_model(endpoint, model, book, imgs, key, 0.2)
        out.write_text(sanitize_markdown(content), encoding="utf-8")
    elif role == "review":
        book = (gdir / f"dispatch-rv-{gi:02d}.md").read_text(encoding="utf-8")
        out = gdir / f"patches-{gi:02d}.json"
        content, usage = call_model(endpoint, model, book, [], key, 0.1)
        data = extract_json(content)
        out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    elif role == "visual":
        book = (gdir / f"dispatch-vs-{gi:02d}.md").read_text(encoding="utf-8")
        imgs = build_images(images_dir, pages)
        out = gdir / f"issues-{gi:02d}.json"
        content, usage = call_model(endpoint, model, book, imgs, key, 0.1)
        data = extract_json(content)
        out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    else:
        sys.exit(f"未知角色: {role}")
    return gi, len(pages), usage


def one_unify(endpoint: str, model: str, key: str, gdir: Path):
    book = (gdir / "dispatch-unify.md").read_text(encoding="utf-8")
    out = gdir / "patches-99.json"
    content, usage = call_model(endpoint, model, book, [], key, 0.1)
    data = extract_json(content)
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return "unify", 0, usage


def main():
    default_base_url = (
        os.getenv("MIMO_BASE_URL")
        or os.getenv("OPENAI_BASE_URL")
        or DEFAULT_BASE_URL
    )
    default_model = (
        os.getenv("MIMO_MODEL")
        or os.getenv("OPENAI_MODEL")
        or DEFAULT_MODEL
    )

    ap = argparse.ArgumentParser(
        description="任务书 → OpenAI 兼容模型接口 → 产出文件（API 并发模式，不走子代理）"
    )
    ap.add_argument("role", choices=["translate", "review", "unify", "visual"])
    ap.add_argument("groups_dir")
    ap.add_argument("--group", default="0", help="只跑指定组，逗号分隔（0=全部）")
    ap.add_argument("--images", default="", help="页面图目录（translate=源图，visual=输出图）")
    ap.add_argument("--base-url", default=default_base_url,
                    help="OpenAI 兼容接口根地址（默认读取 MIMO_BASE_URL / OPENAI_BASE_URL）")
    ap.add_argument("--api-key", default="", help="API 密钥（优先级高于环境变量与 --key-file）")
    ap.add_argument("--key-file", default=str(DEFAULT_KEY_FILE),
                    help="API 密钥文件回退路径（当未设置 MIMO_API_KEY / OPENAI_API_KEY 时读取）")
    ap.add_argument("--model", default=default_model,
                    help="模型名称（默认读取 MIMO_MODEL / OPENAI_MODEL，回退 mimo-v2.6-pro）")
    ap.add_argument("--workers", type=int, default=6)
    args = ap.parse_args()

    endpoint = resolve_endpoint(args.base_url)
    key = resolve_api_key(args.api_key, args.key_file)
    gdir = Path(args.groups_dir)
    index = json.loads((gdir / "_index.json").read_text(encoding="utf-8"))
    if args.group != "0":
        wanted = {int(x) for x in args.group.split(",")}
        index = [i for i in index if i["group"] in wanted]
        if not index:
            sys.exit(f"没有组 {args.group}")
    if args.role == "visual" and not args.images:
        sys.exit("visual 需要 --images")

    t0 = time.time()
    total = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
    tasks = []
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        if args.role == "unify":
            tasks.append(ex.submit(one_unify, endpoint, args.model, key, gdir))
        else:
            for item in index:
                tasks.append(ex.submit(
                    one_task, args.role, endpoint, args.model, key, gdir, item, args.images
                ))
        for fut in as_completed(tasks):
            gi, pages, usage = fut.result()
            total = {k: total.get(k, 0) + usage.get(k, 0) for k in total}
            print(
                f"[api_call] {args.role} 组 {gi}: 页 {pages}  "
                f"tokens in={usage.get('prompt_tokens', 0)} out={usage.get('completion_tokens', 0)}"
            )
    print(
        f"[api_call] {args.role} 完成 {time.time() - t0:.0f}s  "
        f"合计 tokens: in={total['prompt_tokens']} out={total['completion_tokens']} "
        f"total={total['total_tokens']}"
    )


if __name__ == "__main__":
    main()
